const SVG_NS = 'http://www.w3.org/2000/svg';

/**
 * 아이콘 1개를 <svg> 노드로 만든다.
 * ★ 기본은 aria-hidden — 아이콘은 «옆의 글자나 부모의 aria-label» 이 이미 말하고
 *   있는 것을 그림으로 되풀이할 뿐이다. 스크린리더에 두 번 읽히면 안 된다.
 * @param size CSS px. 부모 글자크기를 따라가게 하려면 'em' 을 준다.
 */
export function icon(name: IconName, cls = '', size: number | 'em' = 'em'): SVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 256 256');
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  if (size === 'em') {
    // 1em = 옆 글자와 «같은» 광학 크기. width/height 를 CSS 로 넘겨 배율을 맞춘다.
    svg.setAttribute('width', '1em');
    svg.setAttribute('height', '1em');
  } else {
    svg.setAttribute('width', String(size));
    svg.setAttribute('height', String(size));
  }
  svg.setAttribute('class', `ar-i ${cls}`.trim());
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', PATHS[name]);
  svg.appendChild(path);
  return svg;
}
